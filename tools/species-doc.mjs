#!/usr/bin/env node
/**
 * Generates reference/SPECIES.md from the region packs themselves, so the documentation
 * can never drift out of step with the data — there is exactly one copy of each fact.
 *
 * Run with: node tools/species-doc.mjs
 */
import { register } from 'node:module';
import { pathToFileURL } from 'node:url';
import { writeFileSync } from 'node:fs';

// `module.register` carries a deprecation notice as of Node 24 in favour of the newer,
// synchronous `registerHooks`, but that API does not (yet) support the async transform
// this loader needs. The warning is harmless for a dev-only script; silenced below.
process.removeAllListeners('warning');
register('./tools/ts-loader.mjs', pathToFileURL('./'));

const { REGIONS } = await import('../src/regions/index.ts');
const { validateRegion } = await import('../src/regions/validate.ts');

const issues = REGIONS.flatMap(validateRegion);
if (issues.length) {
  console.error(`${issues.length} validation issue(s) found — fix the pack before regenerating docs:`);
  for (const i of issues) console.error(`  ${i.region} ${i.path}: ${i.message}`);
  process.exit(1);
}

const IUCN_LABELS = {
  NE: 'Not evaluated', DD: 'Data deficient', LC: 'Least concern', NT: 'Near threatened',
  VU: 'Vulnerable', EN: 'Endangered', CR: 'Critically endangered', EW: 'Extinct in the wild', EX: 'Extinct',
};

function speciesRow(s, kind) {
  const local = s.localName ? ` (${s.localName}, ${s.localLanguage})` : '';
  const national = s.national ? `\n  National: ${s.national}` : '';
  return [
    `### ${s.common}${local}`,
    `*${s.scientific}* — ${kind}`,
    ``,
    `- **IUCN status:** ${IUCN_LABELS[s.iucn]} (${s.iucn})${national}`,
    `- **Traits:** ${s.traits.join('; ')}`,
    `- **Fact:** ${s.fact}`,
    `- **Source:** <${s.source}>`,
    ``,
  ].join('\n');
}

let out = `# Species reference\n\n`;
out += `Generated by \`tools/species-doc.mjs\` from the region packs in \`src/regions/\`. `;
out += `Do not edit by hand — edit the pack and regenerate.\n\n`;
out += `Every entry below was checked against the source linked. See \`DECISIONS.md\` for `;
out += `notes on anything corrected or deliberately left out during that check.\n\n`;

for (const region of REGIONS) {
  out += `## ${region.label}\n\n${region.note}\n\n`;
  if (region.excludedSpecies?.length) {
    out += `**Deliberately excluded:**\n\n`;
    for (const e of region.excludedSpecies) {
      out += `- **${e.common}** (*${e.scientific}*) — ${e.reason}\n`;
    }
    out += `\n`;
  }
  for (const biome of region.biomes) {
    out += `### Biome: ${biome.label}\n\n${biome.note}\n\n`;
    out += `#### Plants\n\n`;
    for (const p of biome.plants) out += speciesRow(p, 'plant').replace('###', '#####');
    out += `#### Creatures (unlock order, slot 0 first)\n\n`;
    const sorted = [...biome.creatures].sort((a, b) => a.slot - b.slot);
    for (const c of sorted) out += `**Slot ${c.slot}**\n\n` + speciesRow(c, `creature — ${c.activity}, ${c.zone}`).replace('###', '#####');
  }
}

writeFileSync(new URL('../reference/SPECIES.md', import.meta.url), out);
console.log(`Wrote reference/SPECIES.md (${out.length} bytes)`);
