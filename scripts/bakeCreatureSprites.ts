/**
 * One-off bake: converts every creature's procedural `BodyPlan` + `Palette` into a static
 * Memory-Forest-format `CreatureSprite` ({ pal, frames: [idle, busy], young: [idle, busy] }),
 * sized to land in Memory Forest's own small (5-9px wide) / medium (10-12) / large (<=17)
 * bands, by actually running the existing (tuned, working) procedural generator at a few
 * trial scales and keeping the closest match — not by guessing a formula for how `BodyPlan`
 * dimensions map to final pixel width, since that's exactly what the generator's own margin
 * maths already determines.
 *
 * This is a first-pass, bulk-generated starting point for every species not hand-authored
 * directly (see `src/regions/sprites/handAuthored.ts`) — the review gallery is what flags
 * which of these actually need a real redraw. It is NOT meant to be the final word on any
 * one species; it exists so every creature in the roster has *some* VISITORS-format sprite
 * to review, animate and compare, per the user's Phase 1 instruction.
 *
 * Run: npx esbuild scripts/bakeCreatureSprites.ts --bundle --platform=node --format=esm
 *        --outfile=/tmp/bake.mjs && node /tmp/bake.mjs
 */
import { REGIONS } from '../src/regions';
import { buildProceduralFrames } from '../src/forest/creatureSprite';
import { writeFileSync } from 'node:fs';

type Frame = string[];

function boundingBox(frames: Frame[]): { x0: number; y0: number; x1: number; y1: number } {
  let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
  for (const frame of frames) {
    for (let y = 0; y < frame.length; y++) {
      const row = frame[y];
      for (let x = 0; x < row.length; x++) {
        if (row[x] !== '.') {
          if (x < x0) x0 = x;
          if (x > x1) x1 = x;
          if (y < y0) y0 = y;
          if (y > y1) y1 = y;
        }
      }
    }
  }
  if (x1 < x0) return { x0: 0, y0: 0, x1: 0, y1: 0 };
  return { x0, y0, x1, y1 };
}

/** Crop every frame to one shared bounding box (the union across all of them), so a sprite's
 * frames stay the same size as each other — tight, like Memory Forest's own hand grids. */
function crop(frames: Frame[]): Frame[] {
  const box = boundingBox(frames);
  const w = box.x1 - box.x0 + 1;
  const h = box.y1 - box.y0 + 1;
  return frames.map((frame) => {
    const out: string[] = [];
    for (let y = 0; y < h; y++) {
      const srcY = box.y0 + y;
      const row = frame[srcY] ?? '';
      let line = '';
      for (let x = 0; x < w; x++) line += row[box.x0 + x] ?? '.';
      out.push(line);
    }
    return out;
  });
}

function widthOf(frames: Frame[]): number {
  return Math.max(...frames.map((f) => f.length ? f[0].length : 0), 0);
}

/** Target width band, by the creature's own existing body length — small (5-9px), medium
 * (10-12), large (up to 17), matching Memory Forest's VISITORS sizing exactly. */
function targetWidth(bw: number): number {
  if (bw <= 9) return 7;
  if (bw <= 15) return 11;
  return 16;
}

/** Find the zoomScale that gets `buildProceduralFrames`' cropped adult width closest to
 * `target`, by trying a spread of scales — robust to the generator's own margin formulas
 * rather than guessing them. */
function fitScale(creature: Parameters<typeof buildProceduralFrames>[0], target: number): number {
  let best = 1, bestDiff = Infinity;
  for (let s = 0.3; s <= 3.5; s += 0.05) {
    const [idle, busy] = buildProceduralFrames(creature, 2, s);
    const w = widthOf(crop([idle, busy]));
    const diff = Math.abs(w - target);
    if (diff < bestDiff) { bestDiff = diff; best = s; }
    if (diff === 0) break;
  }
  return best;
}

const entries: string[] = [];
let count = 0;
for (const region of REGIONS) {
  for (const biome of region.biomes) {
    for (const creature of biome.creatures) {
      if (!creature.body || !creature.palette) continue; // already hand-authored upstream
      const [bw] = creature.body.size;
      const target = targetWidth(bw);
      const scale = fitScale(creature, target);
      const adult = crop(buildProceduralFrames(creature, 2, scale));
      const young = crop(buildProceduralFrames(creature, 0, scale));
      const key = `${region.key}:${creature.key}`;
      const palJson = JSON.stringify(creature.palette);
      const framesJson = JSON.stringify(adult);
      const youngJson = JSON.stringify(young);
      const flies = creature.zone === 'sky';
      const hop = creature.body.kind === 'hopper';
      entries.push(
        `  ${JSON.stringify(key)}: { pal: ${palJson}, frames: ${framesJson} as const, young: ${youngJson} as const` +
          (flies ? ', flies: true' : '') +
          (hop ? ', hop: true' : '') +
          ' },'
      );
      count++;
    }
  }
}

const out = `/**
 * Auto-generated by scripts/bakeCreatureSprites.ts — DO NOT hand-edit.
 *
 * A first-pass VISITORS-format sprite for every creature not given a real hand-authored one
 * in handAuthored.ts, baked from the existing (tuned) procedural BodyPlan generator rather
 * than drawn by hand. These are a starting point for the review gallery, not finished art —
 * see DECISIONS.md § "Region packs" and review/gallery.html.
 *
 * Regenerate with:
 *   npx esbuild scripts/bakeCreatureSprites.ts --bundle --platform=node --format=esm --outfile=/tmp/bake.mjs && node /tmp/bake.mjs
 */
import type { CreatureSprite } from '../types';

export const BAKED_SPRITES: Record<string, CreatureSprite> = {
${entries.join('\n')}
};
`;

writeFileSync(new URL('src/regions/sprites/baked.generated.ts', `file://${process.cwd()}/`), out);
console.log(`Baked ${count} creature sprites.`);
