/**
 * The study calendar: excused days, holiday mode, semester schedules.
 *
 * The point of all of this is one rule: **a day you were never going to study is not a day
 * you missed.** An excused day is removed from the health calculation entirely. It does not
 * count as missed, it does not consume a slot in the rolling window (so the window reaches
 * further back past it), it never forms a pond, and it never costs unlock progress.
 *
 * Everything here is pure. State lives in synced plugin storage so a break declared on a
 * laptop is honoured on a phone.
 */

import { dayToISO, isoToDay, weekday, yearOf, MS_PER_DAY } from './day';

export type Severity = 'peaceful' | 'gentle' | 'wild' | 'merciless' | 'custom';

export interface DateRange {
  from: string; // ISO YYYY-MM-DD, inclusive
  to: string; // ISO YYYY-MM-DD, inclusive
  name?: string;
}

export interface StudyPeriod {
  id: string;
  name: string;
  from: string;
  to: string;
  /** Mid-semester breaks inside this period; excused even though the period is on. */
  breaks: DateRange[];
}

export interface PauseState {
  /** ISO date the pause began. */
  from: string;
  /** ISO date the pause ends, inclusive. Omitted means "until I resume". */
  until?: string;
  /** What the backlog looked like when the pause started, so recovery is judged fairly. */
  backlogAtStart?: number;
}

export interface StudyCalendar {
  version: 1;
  pause?: PauseState;
  /** Semesters / trimesters. Empty unless the user set some up. */
  periods: StudyPeriod[];
  /** Uni schedule mode: days outside every period are excused. */
  outsidePeriodsExcused: boolean;
  /** Weekdays never studied. 0 = Sunday. */
  excusedWeekdays: number[];
  /** One-off excused days (sick days, trips). */
  oneOff: string[];
  /** Days forced back to counting, overriding every other rule. */
  unexcused: string[];
  /** Public holidays, editable. Generated by `queenslandHolidays` when the user asks. */
  holidays: string[];
  holidaysEnabled: boolean;
  /** Exam periods: not excused, but weighted up in the health score. */
  boostWeeks: DateRange[];
  /** Days of grace after a pause ends, before backlog counts against you. */
  recoveryGraceDays: number;
}

export const DEFAULT_RECOVERY_GRACE_DAYS = 7;

/** How far back a day may be excused after the fact, outside Merciless. */
export const RETRO_EXCUSE_DAYS = 7;

/** Merciless only: the most days a year that may be excused. */
export const MAX_EXCUSED_PER_YEAR = 60;

export function emptyCalendar(): StudyCalendar {
  return {
    version: 1,
    periods: [],
    outsidePeriodsExcused: false,
    excusedWeekdays: [],
    oneOff: [],
    unexcused: [],
    holidays: [],
    holidaysEnabled: false,
    boostWeeks: [],
    recoveryGraceDays: DEFAULT_RECOVERY_GRACE_DAYS,
  };
}

function inRange(day: number, r: DateRange): boolean {
  return day >= isoToDay(r.from) && day <= isoToDay(r.to);
}

/** Whether a pause covers this day. */
export function pauseCovers(pause: PauseState | undefined, day: number): boolean {
  if (!pause) return false;
  if (day < isoToDay(pause.from)) return false;
  return pause.until == null || day <= isoToDay(pause.until);
}

/** Whether a pause is still running as of `today`. */
export function pauseActive(cal: StudyCalendar, today: number): boolean {
  return pauseCovers(cal.pause, today);
}

/**
 * Is this day excused?
 *
 * `unexcused` wins over everything — it is the explicit "no, I really did mean to study
 * that day" override.
 */
export function isExcused(cal: StudyCalendar, day: number): boolean {
  const iso = dayToISO(day);
  if (cal.unexcused.includes(iso)) return false;
  if (pauseCovers(cal.pause, day)) return true;
  if (cal.oneOff.includes(iso)) return true;
  if (cal.holidaysEnabled && cal.holidays.includes(iso)) return true;
  if (cal.excusedWeekdays.includes(weekday(day))) return true;

  if (cal.periods.length > 0) {
    for (const p of cal.periods) {
      if (day >= isoToDay(p.from) && day <= isoToDay(p.to)) {
        // Inside a semester: only its own mid-semester breaks are excused.
        return p.breaks.some((b) => inRange(day, b));
      }
    }
    // Outside every period.
    if (cal.outsidePeriodsExcused) return true;
  }
  return false;
}

/** Every excused day in `[from, to]`, as a set of day numbers. */
export function excusedDaysIn(cal: StudyCalendar, from: number, to: number): Set<number> {
  const out = new Set<number>();
  for (let d = from; d <= to; d++) if (isExcused(cal, d)) out.add(d);
  return out;
}

/** Whether this day is inside an exam-period boost week. */
export function isBoosted(cal: StudyCalendar, day: number): boolean {
  return cal.boostWeeks.some((r) => inRange(day, r));
}

