export interface ExcuseCheck {
  ok: boolean;
  reason?: string;
}

/**
 * May this day be excused?
 *
 * Outside Merciless, up to `RETRO_EXCUSE_DAYS` back — for when you forget to set the pause
 * before going away. In Merciless, a pause must be set before or on the day, and there is a
 * yearly cap. These are the only places the severity setting restricts what you may do
 * rather than how the grove looks.
 */
export function canExcuse(
  cal: StudyCalendar,
  day: number,
  today: number,
  severity: Severity,
): ExcuseCheck {
  if (severity === 'merciless') {
    if (day < today) {
      return { ok: false, reason: 'In Merciless, a break has to be set before or on the day.' };
    }
    const year = yearOf(day);
    const used = countExcusedInYear(cal, year);
    if (used >= MAX_EXCUSED_PER_YEAR) {
      return {
        ok: false,
        reason: `In Merciless, ${MAX_EXCUSED_PER_YEAR} excused days a year is the limit (${used} used in ${year}).`,
      };
    }
    return { ok: true };
  }
  if (day < today - RETRO_EXCUSE_DAYS) {
    return {
      ok: false,
      reason: `Days can be excused up to ${RETRO_EXCUSE_DAYS} days back. ${dayToISO(day)} is further than that.`,
    };
  }
  return { ok: true };
}

/** Excused days already booked in a calendar year. */
export function countExcusedInYear(cal: StudyCalendar, year: number): number {
  const from = isoToDay(`${year}-01-01`);
  const to = isoToDay(`${year}-12-31`);
  let n = 0;
  for (let d = from; d <= to; d++) if (isExcused(cal, d)) n++;
  return n;
}

