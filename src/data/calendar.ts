/** Start a pause. `until` omitted means indefinite. */
export function startPause(
  cal: StudyCalendar,
  today: number,
  until?: number,
  backlog?: number,
): StudyCalendar {
  return {
    ...cal,
    pause: {
      from: dayToISO(today),
      ...(until != null ? { until: dayToISO(until) } : {}),
      ...(backlog != null ? { backlogAtStart: backlog } : {}),
    },
  };
}

/**
 * End a pause as of today.
 *
 * The pause is *closed*, not deleted: the days it covered stay excused forever, so resuming
 * never retroactively marks a holiday as missed.
 */
export function endPause(cal: StudyCalendar, today: number): StudyCalendar {
  if (!cal.pause) return cal;
  const from = isoToDay(cal.pause.from);
  if (today <= from) {
    // Resumed the same day it started, or earlier: nothing to keep.
    return { ...cal, pause: undefined };
  }
  return { ...cal, pause: { ...cal.pause, until: dayToISO(today - 1) } };
}

/** The day a running pause ends, or `null` if indefinite or not paused. */
export function pauseEndsOn(cal: StudyCalendar, today: number): number | null {
  if (!pauseActive(cal, today)) return null;
  return cal.pause?.until != null ? isoToDay(cal.pause.until) : null;
}

/** A line for the tooltip: "Paused until 24 Feb", "Semester break — progress protected". */
export function pauseLabel(cal: StudyCalendar, today: number): string | null {
  if (pauseActive(cal, today)) {
    const end = pauseEndsOn(cal, today);
    if (end == null) return 'On break — progress protected';
    const d = new Date(end * MS_PER_DAY);
    const month = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'][
      d.getUTCMonth()
    ];
    return `Paused until ${d.getUTCDate()} ${month}`;
  }
  if (!isExcused(cal, today)) return null;
  for (const p of cal.periods) {
    for (const b of p.breaks) {
      if (inRange(today, b)) return `${b.name ?? 'Semester break'} — progress protected`;
    }
  }
  if (cal.periods.length > 0 && cal.outsidePeriodsExcused) {
    return 'Out of semester — progress protected';
  }
  if (cal.holidaysEnabled && cal.holidays.includes(dayToISO(today))) {
    return 'Public holiday — progress protected';
  }
  if (cal.excusedWeekdays.includes(weekday(today))) return 'Rest day — progress protected';
  return 'Excused day — progress protected';
}
